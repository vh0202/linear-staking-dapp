// Deploys and seeds the demo on the LOCAL Hardhat node (http://127.0.0.1:8545, chain 31337).
//
//   npx hardhat node                 # terminal 1
//   npm run deploy:local             # terminal 2
//
// It uses only the node's built-in, publicly known test accounts and mock tokens with an
// open `mint`. It always connects to the `localhost` network and refuses any other chain.
//
// What it sets up:
//   - mock tokens STK (staked) and RWD (rewards), and a LinearStaking pool owned by account #0
//   - 10,000 STK each for test accounts #1..#4
//   - a reward period: 70,000 RWD over 7 days (10,000 RWD per day)
//   - two existing stakers (#2: 2,500 STK, #3: 1,500 STK), so shares are not 100%
//   - frontend/.env.local pointing the front end at the deployment (no secrets in it)

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { network } from "hardhat";
import { formatUnits, getAddress, maxUint256, parseUnits, type Hash } from "viem";

const LOCAL_CHAIN_ID = 31337;
const RPC_URL = "http://127.0.0.1:8545";
const STAKER_FUNDS = parseUnits("10000", 18);
const REWARD_AMOUNT = parseUnits("70000", 18);
const REWARD_DURATION = 7n * 24n * 60n * 60n;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const { viem } = await network.create("localhost");
const publicClient = await viem.getPublicClient();

const chainId = await publicClient.getChainId().catch(() => {
  throw new Error(`No JSON-RPC node at ${RPC_URL}. Start one first with: npx hardhat node`);
});
if (chainId !== LOCAL_CHAIN_ID) {
  throw new Error(`deploy-local only runs against the local Hardhat node (chain ${LOCAL_CHAIN_ID}), got chain ${chainId}`);
}

const [owner, demoUser, stakerA, stakerB, spare] = await viem.getWalletClients();
const mined = async (hash: Promise<Hash>) => publicClient.waitForTransactionReceipt({ hash: await hash });

console.log(`Deploying to chain ${chainId} as ${getAddress(owner.account.address)}`);

const stakingToken = await viem.deployContract("MockERC20", ["Stake Token", "STK", 18]);
const rewardsToken = await viem.deployContract("MockERC20", ["Reward Token", "RWD", 18]);
const staking = await viem.deployContract("LinearStaking", [
  stakingToken.address,
  rewardsToken.address,
  owner.account.address,
]);

for (const wallet of [demoUser, stakerA, stakerB, spare]) {
  await mined(stakingToken.write.mint([wallet.account.address, STAKER_FUNDS]));
}

await mined(rewardsToken.write.mint([owner.account.address, REWARD_AMOUNT]));
await mined(rewardsToken.write.approve([staking.address, REWARD_AMOUNT]));
await mined(staking.write.fundRewards([REWARD_AMOUNT, REWARD_DURATION]));

for (const [wallet, amount] of [
  [stakerA, parseUnits("2500", 18)],
  [stakerB, parseUnits("1500", 18)],
] as const) {
  await mined(stakingToken.write.approve([staking.address, maxUint256], { account: wallet.account }));
  await mined(staking.write.stake([amount], { account: wallet.account }));
}

const deployment = {
  chainId,
  rpcUrl: RPC_URL,
  staking: getAddress(staking.address),
  stakingToken: getAddress(stakingToken.address),
  rewardsToken: getAddress(rewardsToken.address),
  owner: getAddress(owner.account.address),
  demoUser: getAddress(demoUser.account.address),
  periodFinish: Number(await staking.read.periodFinish()),
};

await mkdir(path.join(root, "deployments"), { recursive: true });
await writeFile(path.join(root, "deployments", "localhost.json"), `${JSON.stringify(deployment, null, 2)}\n`);

const envLocal = [
  "# Generated by scripts/deploy-local.ts for the local Hardhat node. Contains no secrets.",
  `NEXT_PUBLIC_CHAIN_ID=${chainId}`,
  `NEXT_PUBLIC_RPC_URL=${RPC_URL}`,
  `NEXT_PUBLIC_STAKING_ADDRESS=${deployment.staking}`,
  "# Local demo only: lets the page connect as a built-in Hardhat test account without a",
  "# wallet extension. The local node signs for that account; no key is in the front end.",
  "NEXT_PUBLIC_ENABLE_DEMO_WALLET=true",
  `NEXT_PUBLIC_DEMO_WALLET_ADDRESS=${deployment.demoUser}`,
  "NEXT_PUBLIC_WALLETCONNECT_PROJECT_ID=",
  "",
].join("\n");
await writeFile(path.join(root, "frontend", ".env.local"), envLocal);

console.log(`
LinearStaking   ${deployment.staking}
Stake token     ${deployment.stakingToken} (STK)
Reward token    ${deployment.rewardsToken} (RWD)
Owner           ${deployment.owner}
Demo wallet     ${deployment.demoUser} holds ${formatUnits(STAKER_FUNDS, 18)} STK
Reward period   ${formatUnits(REWARD_AMOUNT, 18)} RWD over ${REWARD_DURATION / 86_400n} days
Total staked    ${formatUnits(await staking.read.totalStaked(), 18)} STK by two other test accounts

Wrote deployments/localhost.json and frontend/.env.local
`);
